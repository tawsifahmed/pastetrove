import AppKit

/// Watches the system clipboard and writes items back to it.
/// macOS has no "clipboard changed" event, so this polls `changeCount`, which is a cheap integer read.
final class Monitor {
    var paused = false
    var onCapture: ((Capture) -> Void)?

    private let store: Store
    private let pasteboard: NSPasteboard
    private var lastChange: Int
    /// Kept alive while their images are on the clipboard or in a drag.
    private var tiffProviders: [TIFFProvider] = []

    private static let fileList = "io.github.tawsifahmed.pastetrove.file-urls"
    private static let maxSize = 30_000_000

    /// Markers that password managers and similar apps put on data that must not be recorded (nspasteboard.org).
    private static let ignored: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "com.typeit4me.clipping",
        "net.antelle.keeweb",
    ]

    init(store: Store, pasteboard: NSPasteboard = .general) {
        self.store = store
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.25, repeats: true) { [weak self] _ in self?.check() }
        // Slack lets macOS group this wake-up with others, which saves energy.
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
    }

    private func check() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard !paused,
              let types = pasteboard.types?.map(\.rawValue),
              !Self.skips(types, app: app),
              let clip = read(types)
        else { return }
        store.save(clip, app: app, limit: Settings.historyLimit, imageLimit: Settings.imageLimit)
        onCapture?(clip)
    }

    /// Data marked private, or copied in an app you chose to ignore, is never read.
    static func skips(_ types: [String], app: String?) -> Bool {
        types.contains(where: ignored.contains) || app.map(Settings.ignoredApps.contains) == true
    }

    func read(_ types: [String]) -> Capture? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            // A file in another app's private folder is its temporary copy (Telegram does this for photos):
            // it gets deleted later and macOS blocks reading it, so keep the picture itself when there is one.
            if urls.contains(where: { Cache.isOtherAppData($0.path) }), let image = readImage() { return image }
            let list = Data(urls.map(\.absoluteString).joined(separator: "\n").utf8)
            return Capture(kind: .file, text: urls.map(\.path).joined(separator: "\n"), key: list, reps: [(Self.fileList, list)])
        }
        if let string = pasteboard.string(forType: .string),
           string.utf8.count < Self.maxSize,
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            var reps = [(NSPasteboard.PasteboardType.string.rawValue, Data(string.utf8))]
            for type in [NSPasteboard.PasteboardType.rtf, .html] where types.contains(type.rawValue) {
                if let data = pasteboard.data(forType: type), data.count < 5_000_000 {
                    reps.append((type.rawValue, data))
                }
            }
            return Capture(kind: Self.isLink(string) ? .link : .text, text: string, key: Data(string.utf8), reps: reps)
        }
        return readImage()
    }

    private func readImage() -> Capture? {
        // TIFF is uncompressed, so allow it to be larger, but check before converting it.
        if let png = pasteboard.data(forType: .png)
            ?? pasteboard.data(forType: .tiff).flatMap({ $0.count < Self.maxSize * 4 ? Self.png($0) : nil }),
           png.count < Self.maxSize,
           let image = NSBitmapImageRep(data: png) {
            var reps = [(NSPasteboard.PasteboardType.png.rawValue, png)]
            if let thumbnail = Self.thumbnail(png) { reps.append((Store.thumbnailType, thumbnail)) }
            return Capture(kind: .image, text: "Image \(image.pixelsWide)×\(image.pixelsHigh)", key: png, reps: reps)
        }
        return nil
    }

    /// Puts an item back on the clipboard. `plain` drops rich text and keeps only the plain string.
    /// The item keeps its place in the history.
    func write(_ item: Item, plain: Bool) {
        tiffProviders = []
        let entries = writers(item, plain: plain)
        // A broken item never empties the clipboard.
        guard !entries.isEmpty else { return }
        pasteboard.clearContents()
        pasteboard.writeObjects(entries)
        lastChange = pasteboard.changeCount
    }

    /// What a drag carries: one entry per item, and text next to text joined into one, like a multi-paste.
    func dragWriters(_ items: [Item]) -> [(Item, NSPasteboardWriting)] {
        tiffProviders = []
        return Model.pasteGroups(items).flatMap { group -> [(Item, NSPasteboardWriting)] in
            guard group.count > 1 else { return writers(group[0], plain: false).map { (group[0], $0) } }
            let entry = NSPasteboardItem()
            entry.setString(group.map(fullText).joined(separator: "\n"), forType: .string)
            return [(group[0], entry)]
        }
    }

    /// What an item becomes on a pasteboard: its files, its image, or its text with every saved format.
    private func writers(_ item: Item, plain: Bool) -> [NSPasteboardWriting] {
        let reps = store.reps(item.id)
        func data(_ type: String) -> Data? { reps.first { $0.0 == type }?.1 }
        switch item.kind {
        case .file:
            let urls = data(Self.fileList).flatMap { String(data: $0, encoding: .utf8) }?
                .split(separator: "\n").compactMap { URL(string: String($0)) } ?? []
            return urls as [NSURL]
        case .image:
            guard let png = data(NSPasteboard.PasteboardType.png.rawValue) else { return [] }
            // TIFF is made only if an app asks for it: for a large screenshot it is tens of MB and slow to build.
            let entry = NSPasteboardItem()
            entry.setData(png, forType: .png)
            let provider = TIFFProvider(png)
            tiffProviders.append(provider)
            entry.setDataProvider(provider, forTypes: [.tiff])
            return [entry]
        case .text, .link:
            let use = plain ? reps.filter { $0.0 == NSPasteboard.PasteboardType.string.rawValue } : reps
            guard !use.isEmpty else { return [] }
            let entry = NSPasteboardItem()
            for (type, data) in use { entry.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return [entry]
        }
    }

    /// The list holds only the first 2,000 characters of a text; pasting and dragging use all of it.
    func fullText(_ item: Item) -> String {
        store.data(item.id, type: NSPasteboard.PasteboardType.string.rawValue).map { String(decoding: $0, as: UTF8.self) } ?? item.text
    }

    /// Puts plain text on the clipboard without adding it to the history.
    func write(text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChange = pasteboard.changeCount
    }

    /// Small JPEG saved next to each image, so lists never decode the full screenshot.
    private static func thumbnail(_ png: Data) -> Data? {
        guard let image = Cache.scaled(CGImageSourceCreateWithData(png as CFData, nil), Store.thumbnailSize),
              let cgImage = image.cgImage(forProposedRect: nil, context: nil, hints: nil)
        else { return nil }
        return NSBitmapImageRep(cgImage: cgImage).representation(using: .jpeg, properties: [.compressionFactor: 0.8])
    }

    static func isLink(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace),
              let url = URL(string: trimmed),
              let scheme = url.scheme?.lowercased()
        else { return false }
        return (scheme == "http" || scheme == "https") && url.host != nil
    }

    private static func png(_ tiff: Data) -> Data? {
        NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }
}

/// Builds the TIFF copy of a pasted image on request.
private final class TIFFProvider: NSObject, NSPasteboardItemDataProvider {
    private let png: Data

    init(_ png: Data) {
        self.png = png
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation {
            item.setData(tiff, forType: type)
        }
    }
}
